export function build_track_trace_entry(
	action: TrackTraceEntry["action"],
	track?: string,
	status?: TrackTraceEntry["status"],
): TrackTraceEntry {
	return {
		action,
		track,
		status,
		timestamp: new Date().toISOString(),
	};
}

export function get_latest_track_trace(
	branch: Array<{ type: string; customType?: string; data?: unknown }>,
): TrackTraceEntry | undefined {
	for (let index = branch.length - 1; index >= 0; index -= 1) {
		const entry = branch[index];
		if (entry.type !== "custom" || entry.customType !== TRACK_TRACE_ENTRY_TYPE) {
			continue;
		}
		const parsed = track_trace_entry_schema.safeParse(entry.data);
		if (parsed.success) {
			return parsed.data;
		}
	}
	return undefined;
}

export function get_session_track_slug(
	branch: Array<{ type: string; customType?: string; data?: unknown }>,
): string | undefined {
	const latest_trace = get_latest_track_trace(branch);
	if (latest_trace?.action !== "set-active") {
		return undefined;
	}
	return latest_trace.track;
}

export async function restore_track_status(ctx: {
	cwd: string;
	sessionManager: { getBranch: () => Array<{ type: string; customType?: string; data?: unknown }> };
	ui: { setStatus: (key: string, value: string | undefined) => void; notify: (message: string, level: string) => void };
}): Promise<void> {
	const tracks_dir = path.resolve(ctx.cwd, ".pi/tracks");
	const active_track = get_session_track_slug(ctx.sessionManager.getBranch());

	if (!active_track) {
		ctx.ui.setStatus(TRACK_STATUS_KEY, undefined);
		return;
	}

	const track_record = read_track_record_sync_safe(tracks_dir, active_track);
	if (!track_record) {
		ctx.ui.setStatus(TRACK_STATUS_KEY, `🧵 missing:${active_track}`);
		ctx.ui.notify(
			`Active track '${active_track}' is missing or malformed. Run /track list or /track use <name> to repair the binding.`,
			"warning",
		);
		return;
	}

	ctx.ui.setStatus(TRACK_STATUS_KEY, `🧵 ${active_track}`);
}

function read_track_record_sync_safe(tracks_dir: string, slug: string): TrackRecord | null {
	for (const track_record of list_tracks_sync(tracks_dir)) {
		if (track_record.slug === slug) {
			return track_record;
		}
	}
	return null;
}

export async function clear_active_track_if_matches(tracks_dir: string, slug: string): Promise<boolean> {
	const active_track = await get_active_track(tracks_dir);
	if (active_track !== slug) {
		return false;
	}
	await clear_active_track(tracks_dir);
	return true;
}
